/** Ordered structural parity against the upstream festival and traffic modules.
  *
  * Every expected row was produced by executing the upstream JavaScript
  * (`src/world/traffic.js`, `src/world/matsuri.js`) under Node with three 0.185.1 in a fresh
  * context: `streetHeight + reliefAt` for `groundAt`, no platforms or cuts, and a recording context
  * that mirrors `index.js`'s registries.  A tracer replaying that harness reproduces
  * /tmp/upstream-oracle/shotengai-shrine-backdrop-oracle.json row for row, which is what these rows
  * are.
  *
  * Bounding boxes use `Box3` semantics, not per-vertex world transformation: each mesh contributes
  * `geometry.boundingBox` transformed by its `matrixWorld`, unioned.  The two agree on axis-aligned
  * meshes and differ on rotated ones, and the oracle was measured the `Box3` way.
  */
class TrafficAndMatsuriParitySuite extends munit.FunSuite:

