/** Ordered structural parity against the upstream neighbourhood modules.
  *
  * Every expected row was produced by executing the upstream JavaScript
  * (`src/world/{district,details,alleys,restcorner}.js`) under Node with three
  * 0.185.1 in a fresh context: `streetHeight + reliefAt` for `groundAt`, no
  * platforms or cuts, and a recording context that mirrors `index.js`'s
  * registries.  A tracer replaying that harness reproduces
  * /tmp/upstream-oracle/neighbors-oracle.json row for row, which is what these
  * rows are.
  *
  * Bounding boxes use `Box3` semantics, not per-vertex world transformation:
  * each mesh contributes `geometry.boundingBox` transformed by its
  * `matrixWorld`, unioned.  The two agree on axis-aligned meshes and differ on
  * rotated ones, and the oracle was measured the `Box3` way.
  */
class NeighborsParitySuite extends munit.FunSuite:

  override def beforeAll(): Unit = WorldCanvasStub.install()

  private type ChildRow =
    (Int, Int, Int, Int, Int, Int, Int, Vector[Double], Vector[Int])
  private type ColliderRow = (Double, Double, Double, Double, Double, Option[Double])
  private type PlatformRow = (Double, Double, Double, Double, Double)
  private type PlantingRow = (Int, Int, Int, Int, Int, Int)

  final private case class Traced(
    meshCount: Int,
    instancedCount: Int,
    vertexCount: Int,
    multiMatCount: Int,
    groupSliceCount: Int,
    castShadowCount: Int,
    receiveShadowCount: Int,
    bbox: Vector[Double],
    colorDigest: Vector[Int]
  )

  private def round3(value: Double): Double = math.round(value * 1000.0) / 1000.0

  private def traceChild(child: Object3D[?]): Traced =
    child.updateMatrixWorld(js.defined(true))
    val box = new Box3()
    box.makeEmpty()
    var meshCount          = 0
    var instancedCount     = 0
    var vertexCount        = 0
    var multiMatCount      = 0
    var groupSliceCount    = 0
    var castShadowCount    = 0
    var receiveShadowCount = 0
    val colors             = scala.collection.mutable.ArrayBuffer.empty[Int]
    child.traverse { (node: Object3D[Object3DEventMap]) =>
      if ThreeInterop.isMesh(node) then
        meshCount += 1
        ThreeInterop.asInstancedObject(node).foreach(instanced => instancedCount += instanced.count.toInt)
        ThreeInterop.asMesh(node).foreach { mesh =>
          val geometry = ThreeInterop.meshGeometry(mesh)
          vertexCount += ThreeInterop.positionCount(geometry).toInt
          groupSliceCount += geometry.groups.length
          materialColorsOf(mesh).foreach(color => if colors.length < 8 then colors += color)
          multiMatCount += (if hasMaterialArray(mesh) then 1 else 0)
          if geometry.boundingBox == null then geometry.computeBoundingBox()
          geometry.boundingBox match
            case local: Box3 => box.union(local.clone().applyMatrix4(node.matrixWorld))
            case _           => ()
        }
        if node.castShadow then castShadowCount += 1
        if node.receiveShadow then receiveShadowCount += 1
    }
    val bbox =
      if box.isEmpty() then Vector.empty
      else
        Vector(
          round3(box.min.x), round3(box.min.y), round3(box.min.z),
          round3(box.max.x), round3(box.max.y), round3(box.max.z)
        )
    Traced(meshCount, instancedCount, vertexCount, multiMatCount, groupSliceCount,
      castShadowCount, receiveShadowCount, bbox, colors.toVector.take(8))
  end traceChild

  private def materialColorsOf(mesh: Mesh[?, ?, ?]): Vector[Int] =
    mesh.material match
      case materials: js.Array[Material[?]] => materials.toVector.flatMap(colorOf)
      case material: Material[?]            => colorOf(material)
      case _                                => Vector.empty

  private def colorOf(material: Material[?]): Vector[Int] =
    material match
      case basic: MeshBasicMaterial => Vector(basic.color.getHex().toInt)
      case toon: MeshToonMaterial   => Vector(toon.color.getHex().toInt)
      case _                        => Vector.empty

  private def hasMaterialArray(mesh: Mesh[?, ?, ?]): Boolean =
    mesh.material match
      case _: js.Array[Material[?]] => true
      case _                        => false

  private def renderDouble(value: Double): String =
    if value == value.toLong.toDouble then s"${value.toLong}.0" else value.toString

  private def render(traced: Traced): String =
    val bbox   = traced.bbox.map(renderDouble).mkString("Vector(", ", ", ")")
    val colors = traced.colorDigest.mkString("Vector(", ", ", ")")
    s"Traced(${traced.meshCount}, ${traced.instancedCount}, ${traced.vertexCount}, " +
      s"${traced.multiMatCount}, ${traced.groupSliceCount}, ${traced.castShadowCount}, " +
      s"${traced.receiveShadowCount}, $bbox, $colors)"

  private def assertChildren(actual: Vector[Object3D[?]], expected: Vector[ChildRow], where: String): Unit =
    assertEquals(actual.length, expected.length, s"$where top child count")
    actual.zip(expected).zipWithIndex.foreach { case ((child, want), index) =>
      val traced = traceChild(child)
      val row = (traced.meshCount, traced.instancedCount, traced.vertexCount,
        traced.multiMatCount, traced.groupSliceCount, traced.castShadowCount,
        traced.receiveShadowCount, traced.bbox, traced.colorDigest)
      if row != want then fail(s"$where child $index\n  actual   ${render(traced)}\n  expected $want")
    }

  private def assertColliders(actual: Vector[Collider], expected: Vector[ColliderRow], where: String): Unit =
    assertEquals(actual.length, expected.length, s"$where collider count")
    actual.zip(expected).zipWithIndex.foreach { case ((collider, want), index) =>
      val row = (round3(collider.x0), round3(collider.z0), round3(collider.x1),
        round3(collider.z1), round3(collider.top), collider.bottom.map(round3))
      assertEquals(row, want, s"$where collider $index")
    }

  private def assertPlatforms(actual: Vector[Platform], expected: Vector[PlatformRow], where: String): Unit =
    assertEquals(actual.length, expected.length, s"$where platform count")
    actual.zip(expected).zipWithIndex.foreach { case ((platform, want), index) =>
      val row = (round3(platform.x0), round3(platform.x1), round3(platform.z0),
        round3(platform.z1), round3(platform.top))
      assertEquals(row, want, s"$where platform $index")
    }

  private def assertPlanting(actual: Planting, expected: PlantingRow, where: String): Unit =
    val row = (actual.sakura.length, actual.shrubs.length, actual.bamboo.length,
      actual.grove.length, actual.cedar.length, actual.petals.length)
    assertEquals(row, expected, s"$where planting")

